import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const titlePattern = /^(feat|fix|docs|style|refactor|test|chore|build|ci|perf|revert)(\([a-z0-9-]+\))?!?: \S.*[^.]$/;
const issuePattern = /\b(close[sd]?|fix(e[sd])?|resolve[sd]?) #\d+/i;
const maximumTitleLength = 72;
const machineDirective =
  /eslint-disable|@ts-expect-error|@ts-ignore|\/\/\/ <reference|<auto-generated|prettier-ignore|oxlint-disable|webpackChunkName|@vite-ignore|ReSharper disable/;
const slashCommentFiles = /\.(cs|ts|tsx|js|jsx|mjs|proto)$/;
const hashCommentFiles = /(\.(ya?ml|sh|conf|py)|(^|\/)(Dockerfile|[^/]*\.Dockerfile|\.env(\.local)?\.example))$/;
const commentFreeExemptions = /(^|\/)(Migrations|node_modules|dist|bin|obj)\/|\.Designer\.cs$|^docs\/diagrams\//;
const testFile = /(^|\/)tests?\/|\.test\.(ts|tsx|mjs)$/;
const featureCode = /^src\/(Identity|Group|Recommendation|Realtime)Service\/[^/]+\.(API|Services)\/.+\.cs$/;
const migrationFile = /\/Migrations\/\d+_[^/]+\.cs$/;
const migrationOperation = /\bmigrationBuilder\s*\./;
const schemaObjectName = /\[((?:PK|FK|CK|DF|UX|IX|AK|UQ)_\w+)\]/g;
const verifiableOperations = new Set(["CreateTable", "CreateIndex", "AddColumn", "AddForeignKey", "AddCheckConstraint", "AddPrimaryKey", "AddUniqueConstraint", "InsertData"]);

export function parseDiff(diff) {
  const files = new Map();
  let current = null;
  let inHeader = false;
  let line = 0;
  const clean = (text) => text.slice(4).split("\t")[0];
  const fileAt = (path) => {
    const file = files.get(path) ?? { path, added: [], removed: [] };
    files.set(path, file);
    return file;
  };

  for (const text of diff.split("\n")) {
    if (text.startsWith("diff --git ")) {
      inHeader = true;
      current = null;
    } else if (inHeader && /^(rename|copy) to /.test(text)) {
      current = fileAt(text.replace(/^(rename|copy) to /, ""));
    } else if (inHeader && /^Binary files .* and b\/.* differ$/.test(text)) {
      current = fileAt(/ and b\/(.*) differ$/.exec(text)[1]);
    } else if (inHeader && text.startsWith("--- ")) {
      const path = clean(text);
      current = path === "/dev/null" ? null : fileAt(path.replace(/^a\//, ""));
    } else if (inHeader && text.startsWith("+++ ")) {
      const path = clean(text);
      if (path === "/dev/null") {
        if (current) {
          current.deleted = true;
        }
      } else {
        files.delete(current?.path);
        current = fileAt(path.replace(/^b\//, ""));
      }
    } else if (text.startsWith("@@")) {
      inHeader = false;
      line = Number(/\+(\d+)/.exec(text)?.[1] ?? 0);
    } else if (!inHeader && current && text.startsWith("+")) {
      current.added.push({ line, text: text.slice(1) });
      line += 1;
    } else if (!inHeader && current && text.startsWith("-")) {
      current.removed.push(text.slice(1));
    }
  }

  return [...files.values()];
}

function withoutStrings(text) {
  return text
    .replace(/\\./g, "_")
    .replace(/"[^"]*"/g, '""')
    .replace(/'[^']*'/g, "''")
    .replace(/`[^`]*`/g, "``");
}

export function hasComment(path, text) {
  if (commentFreeExemptions.test(path) || machineDirective.test(text)) {
    return false;
  }

  const trimmed = text.trim();
  if (slashCommentFiles.test(path)) {
    return /^\*\//.test(trimmed) || /(^|[^:])\/\/|\/\*/.test(withoutStrings(text));
  }

  if (hashCommentFiles.test(path)) {
    return !/^#!|^# syntax=|^# shellcheck/.test(trimmed) && /(^|\s)#/.test(withoutStrings(text));
  }

  if (path.endsWith(".sql")) {
    return /^(--|\/\*)/.test(trimmed);
  }

  if (/\.(csproj|props|xml)$/.test(path)) {
    return trimmed.includes("<!--");
  }

  return false;
}

function lineRules(path) {
  const rules = [];
  if (path.endsWith(".csproj")) {
    rules.push([/<PackageReference\b[^>]*\bVersion(Override)?=/, "Package versions live only in Directory.Packages.props."]);
  }

  if (path.startsWith("src/") && path.endsWith(".cs") && !commentFreeExemptions.test(path)) {
    rules.push([/\bConsole\.(Write|WriteLine)\(/, "Log through ILogger instead of Console."]);
    rules.push([/\bcatch\s*(\([^)]*\))?\s*\{\s*\}/, "Do not swallow exceptions with an empty catch."]);
    rules.push([/\.Result\b(?!\s*=[^=])|\.GetAwaiter\(\)\.GetResult\(\)|\.Wait\(\)/, "Await instead of blocking on a task."]);
  }

  if (/\/Controllers\/[^/]+\.cs$/.test(path)) {
    rules.push([
      /(\breturn\s+|=>\s*)(Ok|BadRequest|NotFound|Conflict|Unauthorized|Forbid|StatusCode|Json)\(/,
      "Controllers answer through ApiControllerBase helpers and throw coded exceptions for failures.",
    ]);
  }

  if (path.startsWith("src/web/src/") && !testFile.test(path)) {
    rules.push([/\bconsole\.(log|debug|info)\(/, "Remove console logging from the web app."]);
    rules.push([/\bhttps?:\/\/(?!www\.w3\.org)/, "The web app calls relative paths; never hard-code a server address."]);
    if (path.startsWith("src/web/src/features/")) {
      rules.push([/\bfetch\(/, "Call the API through useAuth().api, not fetch."]);
    }
  }

  return rules;
}

function declaration(text) {
  const match = /^\s*(.*?)\b(\w+)\s*=\s*(\d+)\s*(\[[^\]]*\]\s*)?;/.exec(text);
  return match && { type: match[1].trim().replace(/\s+/g, " "), name: match[2], number: match[3] };
}

function protoProblems(file) {
  const added = file.added.map((entry) => entry.text);
  const problems = [];
  for (const removed of file.removed) {
    const field = declaration(removed);
    if (!field) {
      continue;
    }

    const { name, number } = field;
    const kept = added.some((text) => {
      const candidate = declaration(text);
      return candidate?.type === field.type && candidate.name === name && candidate.number === number;
    });
    const reserved = added.some((text) => new RegExp(`\\breserved\\b.*\\b${number}\\b`).test(text));
    if (!kept && !reserved) {
      problems.push({ path: file.path, rule: "proto", message: `Field ${name} = ${number} changed: proto fields may only be added, or removed with reserved.` });
    }
  }

  return problems;
}

function isEmptyMigration(file) {
  const current = file.content?.split("\n") ?? file.added.map((entry) => entry.text);
  const lines = [...current, ...file.removed];
  return lines.some((text) => /\bvoid Up\(/.test(text)) && !lines.some((text) => migrationOperation.test(text));
}

export function declaredSchema(sql) {
  const tables = new Map();
  for (const [, table, body] of sql.matchAll(/CREATE TABLE dbo\.\[(\w+)\] \(([\s\S]*?)\r?\n\);/g)) {
    tables.set(table, new Set([...body.matchAll(/^\s*\[(\w+)\]/gm)].map(([, column]) => column)));
  }

  return { tables, names: new Set([...sql.matchAll(schemaObjectName)].map(([, name]) => name)) };
}

export function undeclaredByMigration(content, schema) {
  const up = /\bvoid Up\(([\s\S]*?)(\bvoid Down\(|$)/.exec(content)?.[1];
  if (up === undefined) {
    return null;
  }

  const undeclared = new Set();
  for (const operation of up.split(migrationOperation).slice(1)) {
    const name = /^(\w+)/.exec(operation)?.[1];
    if (!verifiableOperations.has(name)) {
      return null;
    }

    const created = name === "CreateTable" ? /name:\s*"(\w+)"/.exec(operation)?.[1] : undefined;
    const columns = created ? [...operation.matchAll(/(\w+)\s*=\s*table\.Column</g)].map(([, column]) => [created, column]) : [];
    const added = /^AddColumn<[^>]+>\(\s*name:\s*"(\w+)",\s*table:\s*"(\w+)"/.exec(operation);
    for (const [table, column] of added ? [...columns, [added[2], added[1]]] : columns) {
      if (!schema.tables.get(table)?.has(column)) {
        undeclared.add(`column ${table}.${column}`);
      }
    }

    for (const [, table] of operation.matchAll(/\b(?:table|principalTable):\s*"(\w+)"/g)) {
      if (!schema.tables.has(table)) {
        undeclared.add(`table ${table}`);
      }
    }

    if (created && !schema.tables.has(created)) {
      undeclared.add(`table ${created}`);
    }

    for (const [, objectName] of operation.matchAll(/"((?:PK|FK|CK|DF|UX|IX|AK|UQ)_\w+)"/g)) {
      if (!schema.names.has(objectName)) {
        undeclared.add(objectName);
      }
    }
  }

  return [...undeclared].sort();
}

export function checkFiles(files, { schema } = {}) {
  const problems = [];
  for (const file of files) {
    if (/(^|\/)\.env(\.(?!(local\.)?example$)[^/]+)?$/i.test(file.path)) {
      problems.push({ path: file.path, rule: "secrets", message: "Never commit environment files; only the .example templates belong in the repository." });
    }

    const rules = lineRules(file.path);
    for (const { line, text } of file.added) {
      if (hasComment(file.path, text)) {
        problems.push({ path: file.path, line, rule: "no-comments", message: "This project keeps knowledge in names and tests, not comments." });
      }

      for (const [pattern, message] of rules) {
        if (pattern.test(text)) {
          problems.push({ path: file.path, line, rule: "code", message });
        }
      }
    }

    if (rules.some(([pattern]) => pattern.source.includes("catch"))) {
      const joined = file.added.map((entry) => entry.text).join("\n");
      if (!file.added.some(({ text }) => /\bcatch\s*(\([^)]*\))?\s*\{\s*\}/.test(text)) && /\bcatch\s*(\([^)]*\))?\s*\{\s*\}/.test(joined)) {
        problems.push({ path: file.path, rule: "code", message: "Do not swallow exceptions with an empty catch." });
      }
    }

    if (file.path.endsWith(".proto") && !file.deleted) {
      problems.push(...protoProblems(file));
    }
  }

  const paths = files.map((file) => file.path);
  const changesContent = (file) => file.added.length > 0 || file.removed.length > 0;
  const migrations = files.filter((file) => migrationFile.test(file.path) && !file.path.endsWith(".Designer.cs") && changesContent(file) && !isEmptyMigration(file));
  const declared = schema === undefined ? null : declaredSchema(schema);
  let needsSchemaChange = false;
  for (const migration of migrations) {
    const verifiable = declared && migration.content !== undefined && !migration.removed.some((text) => migrationOperation.test(text));
    const undeclared = verifiable ? undeclaredByMigration(migration.content, declared) : null;
    if (undeclared === null) {
      needsSchemaChange = true;
    } else if (undeclared.length > 0) {
      problems.push({ path: migration.path, rule: "schema", message: `This migration creates ${undeclared.join(", ")}, which database/schema.sql does not declare.` });
    }
  }

  if (needsSchemaChange && !paths.includes("database/schema.sql")) {
    problems.push({ path: "database/schema.sql", rule: "schema", message: "A migration that changes or drops structure must update database/schema.sql in the same pull request." });
  }

  return problems;
}

export function checkPullRequest({ title, body, author, paths }) {
  if (author === "dependabot[bot]") {
    return [];
  }

  const problems = [];
  if (!titlePattern.test(title)) {
    problems.push({ rule: "title", message: "Title must look like 'feat(group): add course search', without a final period; it becomes the commit on main." });
  }

  if (title.length > maximumTitleLength) {
    problems.push({ rule: "title", message: `Title has ${title.length} characters; the limit is ${maximumTitleLength}.` });
  }

  if (/^(feat|fix)\b/.test(title)) {
    if (!issuePattern.test(body ?? "")) {
      problems.push({ rule: "issue", message: "feat and fix pull requests must link their issue, for example 'Closes #20'." });
    }

    if (paths.some((path) => featureCode.test(path)) && !paths.some((path) => path.startsWith("tests/"))) {
      problems.push({ rule: "tests", message: "feat and fix pull requests that change a service must change tests too." });
    }
  }

  return problems;
}

function annotate({ path, line, rule, message }) {
  const location = path ? `file=${path},${line ? `line=${line},` : ""}` : "";
  console.log(`::error ${location}title=${rule}::${message}`);
}

function main() {
  const { BASE_SHA: base, PR_TITLE: title = "", PR_BODY: body = "", PR_AUTHOR: author = "" } = process.env;
  if (!base) {
    throw new Error("BASE_SHA is required.");
  }

  const diff = execFileSync("git", ["-c", "core.quotePath=false", "diff", "--unified=0", "--no-color", "--no-ext-diff", `${base}...HEAD`], {
    encoding: "utf8",
    maxBuffer: 1 << 28,
  });
  const files = parseDiff(diff).map((file) =>
    migrationFile.test(file.path) && existsSync(file.path) ? { ...file, content: readFileSync(file.path, "utf8") } : file,
  );
  const schema = existsSync("database/schema.sql") ? readFileSync("database/schema.sql", "utf8") : undefined;
  const problems = [...checkFiles(files, { schema }), ...checkPullRequest({ title, body, author, paths: files.filter((file) => file.added.length > 0).map((file) => file.path) })];
  problems.forEach(annotate);
  if (problems.length > 0) {
    console.error(`${problems.length} convention problem(s). See CONTRIBUTING.md.`);
    process.exit(1);
  }

  console.log(`Conventions hold across ${files.length} changed file(s).`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
