import assert from "node:assert/strict";
import { test } from "node:test";
import { checkFiles, checkPullRequest, hasComment, parseDiff } from "./check-conventions.mjs";

const fileWith = (path, ...texts) => ({ path, removed: [], added: texts.map((text, index) => ({ line: index + 1, text })) });
const rulesFor = (files) => checkFiles(files).map((problem) => problem.rule);

test("finds new comments in every kind of source file", () => {
  assert.equal(hasComment("src/A.cs", "// explains the code"), true);
  assert.equal(hasComment("src/A.cs", "var a = 1; // explains the code"), true);
  assert.equal(hasComment("src/A.cs", "/// <summary>docs</summary>"), true);
  assert.equal(hasComment("src/web/src/a.ts", "/* block */"), true);
  assert.equal(hasComment("docker-compose.yml", "  # note"), true);
  assert.equal(hasComment("database/schema.sql", "-- note"), true);
  assert.equal(hasComment("src/A.csproj", "<!-- note -->"), true);
});

test("keeps machine directives, urls and strings that only look like comments", () => {
  assert.equal(hasComment("src/web/src/a.ts", "// eslint-disable-next-line no-console"), false);
  assert.equal(hasComment("src/web/src/a.ts", "// @ts-expect-error the library type is wrong"), false);
  assert.equal(hasComment("scripts/a.sh", "#!/usr/bin/env bash"), false);
  assert.equal(hasComment("src/A.cs", 'var url = "http://group-service:8081";'), false);
  assert.equal(hasComment("src/A.cs", 'var text = "a // b";'), false);
  assert.equal(hasComment("src/web/src/a.ts", "const pattern = `/* ${glob}`;"), false);
  assert.equal(hasComment("src/Group/Migrations/1_Add.cs", "// <auto-generated />"), false);
  assert.equal(hasComment("src/Group/Migrations/1_Add.cs", "// generated explanation"), false);
  assert.equal(hasComment("README.md", "# Title"), false);
});

test("rejects package versions outside the central file", () => {
  assert.deepEqual(rulesFor([fileWith("src/A/A.csproj", '<PackageReference Include="Foo" Version="1.0.0" />')]), ["code"]);
  assert.deepEqual(rulesFor([fileWith("src/A/A.csproj", '<PackageReference Include="Foo" />')]), []);
});

test("rejects silent failures and blocking calls in services", () => {
  assert.deepEqual(rulesFor([fileWith("src/GroupService/A.cs", "catch { }")]), ["code"]);
  assert.deepEqual(rulesFor([fileWith("src/GroupService/A.cs", "catch (Exception) {}")]), ["code"]);
  assert.deepEqual(rulesFor([fileWith("src/GroupService/A.cs", "Console.WriteLine(value);")]), ["code"]);
  assert.deepEqual(rulesFor([fileWith("src/GroupService/A.cs", "var value = task.Result;")]), ["code"]);
  assert.deepEqual(rulesFor([fileWith("src/GroupService/A.cs", "var value = await task;")]), []);
});

test("rejects controllers that bypass the response envelope", () => {
  assert.deepEqual(rulesFor([fileWith("src/GroupService/G.API/Controllers/A.cs", "return Ok(model);")]), ["code"]);
  assert.deepEqual(rulesFor([fileWith("src/GroupService/G.API/Controllers/A.cs", "return BadRequest(error);")]), ["code"]);
  assert.deepEqual(rulesFor([fileWith("src/GroupService/G.API/Controllers/A.cs", 'return Success(model, "Loaded");')]), []);
});

test("rejects web code that hard-codes a server or skips the api client", () => {
  assert.deepEqual(rulesFor([fileWith("src/web/src/features/a/A.tsx", 'await fetch("/api/v1/semesters");')]), ["code"]);
  assert.deepEqual(rulesFor([fileWith("src/web/src/shared/a.ts", 'const url = "https://exe.example.com";')]), ["code"]);
  assert.deepEqual(rulesFor([fileWith("src/web/src/features/a/A.tsx", "console.log(value);")]), ["code"]);
  assert.deepEqual(rulesFor([fileWith("src/web/src/features/a/A.tsx", 'await api.get("/api/v1/semesters");')]), []);
});

test("requires schema.sql to move with a migration", () => {
  const migration = fileWith("src/GroupService/G.Repositories/Data/Migrations/20261105_AddCourses.cs", "x");
  assert.deepEqual(rulesFor([migration]), ["schema"]);
  assert.deepEqual(rulesFor([migration, fileWith("database/schema.sql", "CREATE TABLE Courses (Id int);")]), []);
});

test("protects existing proto field numbers", () => {
  const changed = { path: "a.proto", removed: ["  string id = 1;"], added: [{ line: 1, text: "  string id = 2;" }] };
  const reserved = { path: "a.proto", removed: ["  string id = 1;"], added: [{ line: 1, text: "  reserved 1;" }] };
  const added = { path: "a.proto", removed: [], added: [{ line: 1, text: "  string extra = 9;" }] };
  assert.deepEqual(rulesFor([changed]), ["proto"]);
  assert.deepEqual(rulesFor([reserved]), []);
  assert.deepEqual(rulesFor([added]), []);
});

test("rejects a committed env file but not the example", () => {
  assert.deepEqual(rulesFor([fileWith(".env", "A=1")]), ["secrets"]);
  assert.deepEqual(rulesFor([fileWith(".env.example", "A=1")]), []);
});

test("checks the title that becomes the commit on main", () => {
  const rules = (title) => checkPullRequest({ title, body: "Closes #1", author: "member", paths: [] }).map((problem) => problem.rule);
  assert.deepEqual(rules("feat(group): add course search"), []);
  assert.deepEqual(rules("ci: tighten the checks"), []);
  assert.deepEqual(rules("add course search"), ["title"]);
  assert.deepEqual(rules("feat: add course search."), ["title"]);
  assert.deepEqual(rules(`feat: ${"x".repeat(80)}`), ["title"]);
});

test("feature work links an issue and carries tests", () => {
  const service = "src/GroupService/ExeGroup.Group.Services/Courses/CourseService.cs";
  const rules = (title, body, paths) => checkPullRequest({ title, body, author: "member", paths }).map((problem) => problem.rule);
  assert.deepEqual(rules("feat: add courses", "", []), ["issue"]);
  assert.deepEqual(rules("feat: add courses", "Closes #19", [service]), ["tests"]);
  assert.deepEqual(rules("feat: add courses", "closes #19", [service, "tests/ExeGroup.Group.IntegrationTests/C.cs"]), []);
  assert.deepEqual(rules("docs: explain courses", "", [service]), []);
});

test("dependency bots are only held to the code rules", () => {
  assert.deepEqual(checkPullRequest({ title: "Bump a long dependency title.", body: "", author: "dependabot[bot]", paths: [] }), []);
});

test("reads added and removed lines from a real diff", () => {
  const diff = [
    "diff --git a/src/A.cs b/src/A.cs",
    "--- a/src/A.cs",
    "+++ b/src/A.cs",
    "@@ -3 +3,2 @@ context",
    "-old line",
    "+new line",
    "+// second",
    "diff --git a/gone.txt b/gone.txt",
    "--- a/gone.txt",
    "+++ /dev/null",
    "@@ -1 +0,0 @@",
    "-removed",
  ].join("\n");
  const [file] = parseDiff(diff);
  assert.equal(file.path, "src/A.cs");
  assert.deepEqual(file.removed, ["old line"]);
  assert.deepEqual(file.added, [{ line: 3, text: "new line" }, { line: 4, text: "// second" }]);
});
