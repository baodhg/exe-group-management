def _in(values):
    return "(" + ", ".join(f"'{v}'" for v in values) + ")"


def col(name, sqltype, nullable=False, key="", default=None, desc=""):
    return {"name": name, "type": sqltype, "null": nullable, "key": key, "default": default, "desc": desc}


