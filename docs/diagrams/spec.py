"""Design data for the EXE Group Management System, version 3.2 (single source for the ER diagrams,
database/schema.sql and the design document).

Roles: Administrator (the Admin actor; the "moderator" of the lecturer's feedback: accounts, setup, coordination,
finalize), Lecturer (read-only view of the courses they teach), Student (a student may lead a room).
Terminology follows FAP: Subject (e.g. EXE101) - Course = a subject taught to one class (e.g. SE1919) in one
semester - Room = an admin-created slot that becomes an official group when the course is finalized.
Major is stored per semester (SemesterStudents.MajorId), not in IdentityDb. Applications (JoinRequests) live in
GroupDb next to the rooms, so approving one is a single local transaction. RoomMembers keeps ended memberships.
Group Service publishes its events through OutboxEvents; the Realtime Service consumes them.
"""

